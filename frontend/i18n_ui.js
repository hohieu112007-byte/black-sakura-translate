  let _curLang = localStorage.getItem("sakuga_ui_lang") === "en" ? "en" : "vi";

  function getUiLang() {
    return _curLang;
  }

  function tUI(key, vars = null) {
    const tbl = DICT[_curLang] || DICT.vi;
    let out = tbl[key] ?? DICT.vi[key] ?? key;
    if (vars && typeof vars === "object") {
      for (const [k, v] of Object.entries(vars)) {
        out = out.replaceAll(`{${k}}`, String(v ?? ""));
      }
    }
    return out;
  }

  function applyUiLanguageToDom(lang) {
    _curLang = lang === "en" ? "en" : "vi";
    localStorage.setItem("sakuga_ui_lang", _curLang);
    document.documentElement.lang = _curLang;

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const k = el.getAttribute("data-i18n");
      if (k) el.textContent = tUI(k);
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const k = el.getAttribute("data-i18n-html");
      if (k) el.innerHTML = tUI(k);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const k = el.getAttribute("data-i18n-placeholder");
      if (k) el.setAttribute("placeholder", tUI(k));
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const k = el.getAttribute("data-i18n-title");
      if (k) el.setAttribute("title", tUI(k));
    });
    document.querySelectorAll("[data-i18n-label]").forEach((el) => {
      const k = el.getAttribute("data-i18n-label");
      if (k) el.setAttribute("label", tUI(k));
    });
    document.querySelectorAll("[data-i18n-done-label]").forEach((el) => {
      const k = el.getAttribute("data-i18n-done-label");
      if (k) el.setAttribute("done-label", tUI(k));
    });
    document.querySelectorAll("[data-i18n-text]").forEach((el) => {
      const k = el.getAttribute("data-i18n-text");
      if (k) el.setAttribute("text", tUI(k));
    });
    document.querySelectorAll("#uiLangSwitcher .lang-btn").forEach((btn) => {
      btn.classList.toggle("active", btn.dataset.langPick === _curLang);
    });
  }

  window.SAKUGA_I18N = DICT;
  window.getUiLang = getUiLang;
  window.tUI = tUI;
  window.applyUiLanguageToDom = applyUiLanguageToDom;
